#!/usr/bin/env node
/**
 * Turns the copy scanner's own rule table into copy-rules.generated.ts.
 *
 *   node lib/backstage/marketing/copy-rules.build.mjs           write it
 *   node lib/backstage/marketing/copy-rules.build.mjs --check   exit 1 if stale
 *
 * Why this exists: the back end has to check a caption or an email against
 * the copy rules at the moment it is saved, with the SAME rules the scanner
 * (legal/scripts/audit-copy.mjs) applies to the site. The scanner is a
 * command-line script. It exports nothing, and loading it runs it, so it
 * cannot be imported by the app. Until it exports its rule table, this script
 * lifts the table out of it, untouched, and writes it down as a module the
 * app can bundle (the same way scripts/embed-migrations.mjs carries the SQL).
 *
 * Nothing here is typed in by hand. The rules are read from the scanner's
 * own `RULES` and `TERMS_OF_ART` values, by loading a temporary copy of the
 * scanner whose last line (the one that runs it) is swapped for an export.
 * tests/backstage/marketing.test.ts runs `--check`, so a rule changed in the
 * scanner and not carried over here fails the build, and the same test puts
 * the same sentences through the scanner and through the back end's check
 * and compares the answers.
 */
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

import * as prettier from "prettier";

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(HERE, "..", "..", "..");
const SCANNER = join(ROOT, "legal", "scripts", "audit-copy.mjs");
const OUT = join(HERE, "copy-rules.generated.ts");
const rel = (file) => relative(ROOT, file).split("\\").join("/");

/** The statement that makes the scanner run itself when it is loaded. */
const RUNS_ITSELF = "process.exitCode = await main(process.argv.slice(2));";

async function liftFromScanner() {
  const source = readFileSync(SCANNER, "utf8");
  const at = source.lastIndexOf(RUNS_ITSELF);
  if (at === -1) {
    throw new Error(
      `${rel(SCANNER)} no longer ends the way this script expects, so its rules cannot be lifted out. If it now exports RULES and TERMS_OF_ART, import them in lib/backstage/marketing/copy-check.ts and delete this script and the generated file.`,
    );
  }
  const lifted =
    source.slice(0, at) +
    "export { RULES, TERMS_OF_ART, MASK };\n" +
    source.slice(at + RUNS_ITSELF.length);

  const dir = mkdtempSync(join(tmpdir(), "qp-copy-rules-"));
  try {
    const file = join(dir, "audit-copy.lifted.mjs");
    writeFileSync(file, lifted);
    return await import(pathToFileURL(file).href);
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
}

function text(value, what) {
  if (typeof value !== "string" || value === "") {
    throw new Error(`The scanner has a rule with no ${what}.`);
  }
  return value;
}

function pattern(value, what) {
  if (!(value instanceof RegExp)) {
    throw new Error(`The scanner has ${what} with no pattern.`);
  }
  return { source: value.source, flags: value.flags };
}

async function build() {
  const scanner = await liftFromScanner();
  if (!Array.isArray(scanner.RULES) || scanner.RULES.length === 0) {
    throw new Error("The scanner has no rules to lift.");
  }
  if (!Array.isArray(scanner.TERMS_OF_ART)) {
    throw new Error("The scanner has no list of terms of art.");
  }

  const rules = scanner.RULES.map((rule) => {
    const id = text(rule.id, "id");
    if (rule.severity !== "banned" && rule.severity !== "restricted") {
      throw new Error(`${id} is neither banned nor restricted.`);
    }
    if (rule.applies !== "every-surface" && rule.applies !== "consumer-only") {
      throw new Error(`${id} does not say which surfaces it applies to.`);
    }
    return {
      id,
      severity: rule.severity,
      applies: rule.applies,
      ...pattern(rule.re, id),
      why: text(rule.why, `reason (${id})`),
      law: text(rule.src, `source (${id})`),
    };
  });

  const terms = scanner.TERMS_OF_ART.map((term) => {
    const id = text(term.id, "id");
    if (!Array.isArray(term.rules) || term.rules.length === 0) {
      throw new Error(`${id} does not name the rules it excuses.`);
    }
    return {
      id,
      rules: term.rules.map((rule) => text(rule, `rule (${id})`)),
      ...pattern(term.re, id),
      why: text(term.why, `reason (${id})`),
    };
  });

  const body = `// copy-audit-ignore-file
/**
 * GENERATED by ${rel(fileURLToPath(import.meta.url))} from
 * ${rel(SCANNER)}. Do not edit.
 *
 * This is the copy scanner's own rule table, lifted out so the back end can
 * check a caption, an email or a review at the moment it is saved. After a
 * rule changes in the scanner, run:
 *
 *   node ${rel(fileURLToPath(import.meta.url))}
 *
 * tests/backstage/marketing.test.ts fails while this file is out of step.
 *
 * It has to spell out every word the rules look for, so the scanner skips it
 * (the marker on the first line), the same way it skips itself.
 */

export type CopyRule = {
  /** Matches the heading in legal/COPY-RULES.md. */
  readonly id: string;
  /** banned: never passes. restricted: passes once a person has checked it. */
  readonly severity: "banned" | "restricted";
  /**
   * Where the scanner enforces it in the repository. Copy checked at save
   * time is always treated as something a customer will read, so both kinds
   * apply to it.
   */
  readonly applies: "every-surface" | "consumer-only";
  /** The pattern, as \`new RegExp(source, flags)\`. */
  readonly source: string;
  readonly flags: string;
  readonly why: string;
  /** The law it comes from. */
  readonly law: string;
};

/** A fixed phrase that contains a scanned word but is not the claim. */
export type CopyTermOfArt = {
  readonly id: string;
  /** The rules it excuses, and no others. */
  readonly rules: readonly string[];
  readonly source: string;
  readonly flags: string;
  readonly why: string;
};

/**
 * The character the scanner puts where one piece of text ends and the next
 * begins, so no rule can match across the gap.
 */
export const SEGMENT_BREAK = ${JSON.stringify(text(scanner.MASK, "segment break"))};

export const COPY_RULES: readonly CopyRule[] = ${JSON.stringify(rules, null, 2)};

export const COPY_TERMS_OF_ART: readonly CopyTermOfArt[] = ${JSON.stringify(terms, null, 2)};
`;

  const options = (await prettier.resolveConfig(OUT)) ?? {};
  return prettier.format(body, { ...options, filepath: OUT });
}

const wanted = await build();

if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = readFileSync(OUT, "utf8");
  } catch {
    current = "";
  }
  if (current !== wanted) {
    console.error(
      `${rel(OUT)} is out of step with ${rel(SCANNER)}. Run: node ${rel(fileURLToPath(import.meta.url))}`,
    );
    process.exit(1);
  }
  console.log(`${rel(OUT)} is in step with the scanner.`);
} else {
  writeFileSync(OUT, wanted);
  console.log(`wrote ${rel(OUT)}.`);
}

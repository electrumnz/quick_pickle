/**
 * M38 — the consumer side and the trade side are two agents, not one agent with
 * a tone switch.
 *
 * The claim being tested is specific: Ari (B2C) and Vic (B2B) differ in prompt,
 * in tools, in memory and in what success means, and neither can reach into the
 * other's work. A single agent with two voices would fail every assertion below.
 *
 * Writes `lib/agents/roster/evidence/11-b2c-b2b-separation.txt`.
 */

import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";

import { afterAll, beforeAll, describe, expect, it } from "vitest";

import type { RosterRole } from "@/lib/agents/roster";

import {
  createRosterHarness,
  openRun,
  runRole,
  type RosterHarness,
} from "./support/harness";

const EVIDENCE = resolve(
  process.cwd(),
  "lib/agents/roster/evidence/11-b2c-b2b-separation.txt",
);

let harness: RosterHarness;
const lines: string[] = [];

function roleFor(slug: string): RosterRole {
  const role = harness.roster.roles.find(
    (candidate) => candidate.definition.slug === slug,
  );
  if (role === undefined) throw new Error(`no role ${slug}`);
  return role;
}

beforeAll(async () => {
  harness = await createRosterHarness();
}, 120_000);

afterAll(async () => {
  mkdirSync(dirname(EVIDENCE), { recursive: true });
  writeFileSync(
    EVIDENCE,
    `${[
      "=".repeat(78),
      "M38 — THE CONSUMER AGENT AND THE TRADE AGENT ARE SEPARATE",
      "=".repeat(78),
      "Generated by tests/roster/separation.test.ts. Every value below is read off",
      "the definitions and the runs, not asserted by hand.",
      "",
      ...lines,
    ]
      .join("\n")
      .replace(
        /[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}/gi,
        "id#1",
      )
      .trimEnd()}\n`,
    "utf8",
  );
  await harness.close();
});

describe("M38 the two sides are genuinely separate agents", () => {
  it("has two definitions, not one with a switch", () => {
    const ari = roleFor("marketing");
    const vic = roleFor("trade");

    expect(ari.definition.slug).not.toBe(vic.definition.slug);
    expect(ari.audience).toBe("b2c");
    expect(vic.audience).toBe("b2b");
    expect(ari.definition.systemPrompt).not.toBe(vic.definition.systemPrompt);
    expect(ari.measure).not.toBe(vic.measure);
    expect(ari.memory).not.toBe(vic.memory);

    lines.push(
      "-".repeat(78),
      "IDENTITY",
      "-".repeat(78),
      `  Ari  ${ari.definition.jobTitle} (${ari.definition.slug}), audience ${ari.audience}`,
      `  Vic  ${vic.definition.jobTitle} (${vic.definition.slug}), audience ${vic.audience}`,
      "",
      `  Ari measured on: ${ari.measure}`,
      `  Vic measured on: ${vic.measure}`,
      "",
      `  Ari memory: ${ari.memory}`,
      `  Vic memory: ${vic.memory}`,
      "",
    );
  });

  it("gives them different prompts, built for different readers", () => {
    const ari = roleFor("marketing").definition.systemPrompt;
    const vic = roleFor("trade").definition.systemPrompt;

    // Each carries its own role instructions.
    expect(ari).toContain("You draft social captions, emails and product copy");
    expect(vic).toContain("You build and work the trade list");
    expect(ari).not.toContain("Qualify before you approach");
    expect(vic).toContain("Qualify before you approach");

    // Each leads with its own customer's script.
    expect(ari.indexOf("DIRECT CUSTOMER")).toBeLessThan(
      ari.indexOf("TRADE BUYER"),
    );
    expect(vic.indexOf("TRADE BUYER")).toBeLessThan(
      vic.indexOf("DIRECT CUSTOMER"),
    );

    // Only the trade side is given the market model to target from.
    expect(vic).toContain("MARKET SIZING");
    expect(ari).not.toContain("MARKET SIZING");

    lines.push(
      "-".repeat(78),
      "PROMPTS",
      "-".repeat(78),
      `  Ari's prompt is ${String(ari.length)} characters; Vic's is ${String(vic.length)}. They are not the same text.`,
      `  Ari leads with the DIRECT CUSTOMER script; Vic leads with the TRADE BUYER script.`,
      `  "Qualify before you approach: a spirits-led list, 40 seats or more" is in`,
      `  Vic's instructions and nowhere in Ari's.`,
      `  Both are given both BrandScript audiences — an agent should know the other`,
      `  customer exists — but each leads with its own and is instructed for it.`,
      `  The market model (TAM/SAM/SOM) is in Vic's prompt only — a consumer campaign`,
      `  does not target a count of venues.`,
      "",
    );
  });

  it("gives them disjoint tools, except reading the range and asking a colleague", () => {
    const ari = roleFor("marketing").definition.tools;
    const vic = roleFor("trade").definition.tools;
    const shared = ari.filter((tool) => vic.includes(tool));

    // `hand_off` is held by all eight roles and does not soften this. It gives
    // neither of them the other's tools: it names a KIND OF WORK, the router
    // resolves it to whoever advertises it, and that agent does its own job
    // under its own prompt, its own grants and its own approvals. Ari asking
    // for wholesale work does not let Ari read an account's file or send a
    // venue anything — it opens a run of Vic's, and Vic's own gate still holds.
    // That is the same boundary `handsOverTo` describes in prose.
    expect(shared).toEqual(["read_catalogue", "hand_off"]);
    expect(vic).toContain("read_account_memory");
    expect(vic).toContain("save_account_note");
    expect(ari).not.toContain("read_account_memory");
    expect(ari).toContain("queue_campaign_email");
    expect(vic).not.toContain("queue_campaign_email");

    lines.push(
      "-".repeat(78),
      "TOOLS",
      "-".repeat(78),
      `  Ari  ${ari.join(", ")}`,
      `  Vic  ${vic.join(", ")}`,
      `  Shared: ${shared.join(", ")} — the price list, and the ability to ask`,
      "  whoever does a job to do it. Neither gains the other's tools by asking:",
      "  a handoff opens a run of the OTHER role, under that role's own grants.",
      "  Only Vic can read an account's history or write to its file. Only Ari can",
      "  send to the customer list. Neither has the other's channel.",
      "",
    );
  });

  it("refuses each of them the other's tool at run time", async () => {
    const cases: { readonly agent: string; readonly tool: string }[] = [
      { agent: "marketing", tool: "queue_trade_outreach" },
      { agent: "trade", tool: "queue_campaign_email" },
    ];
    lines.push("-".repeat(78), "CROSSING OVER", "-".repeat(78));

    for (const attempt of cases) {
      const run = await openRun(harness, roleFor(attempt.agent));
      const call = await run.store.createToolCall({
        runId: run.runId,
        messageId: null,
        toolName: attempt.tool,
        arguments: { anything: "at all" },
        isMutation: true,
        status: "pending",
      });
      const gate = await run.platform.runtime.gateToolCall(run.runId, call.id);
      expect(gate.type).toBe("refused");
      expect(run.outbox.externalCount()).toBe(0);
      lines.push(
        `  ${attempt.agent} calling ${attempt.tool}:`,
        `    REFUSED — ${gate.type === "refused" ? gate.reason : "?"}`,
      );
    }
    lines.push("");
  }, 60_000);

  it("produces different work from the same business", async () => {
    const ariRun = await runRole(harness, roleFor("marketing"));
    const vicRun = await runRole(harness, roleFor("trade"));

    const campaign = ariRun.outbox.of("campaign_email")[0];
    const outreach = vicRun.outbox.of("trade_outreach")[0];
    expect(campaign).toBeDefined();
    expect(outreach).toBeDefined();

    const campaignBody = String(campaign?.payload["body"] ?? "");
    const outreachBody = String(outreach?.payload["body"] ?? "");
    expect(campaignBody).not.toBe(outreachBody);
    // The trade approach is addressed to a named person at a named venue; the
    // campaign is addressed to nobody in particular.
    expect(outreachBody).toContain("A case is six bottles");
    expect(campaignBody).not.toContain("A case is six bottles");

    lines.push(
      "-".repeat(78),
      "WHAT EACH ONE ACTUALLY WROTE, ON THE SAME DAY, FROM THE SAME DATABASE",
      "-".repeat(78),
      "  ARI — to the customer list, anonymous, from the BrandScript:",
      ...campaignBody.split("\n").map((line) => `      ${line}`),
      "",
      `  VIC — to ${String(outreach?.payload["account"] ?? "")}, by name, from that account's file:`,
      ...outreachBody.split("\n").map((line) => `      ${line}`),
      "",
      "  Neither could have written the other's. Ari cannot see an account; Vic",
      "  cannot reach the customer list.",
    );
  }, 60_000);
});

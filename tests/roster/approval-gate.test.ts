/**
 * THE SAFETY PROPERTY, ATTACKED.
 *
 * > No agent may send anything externally or mutate the storefront without an
 * > `approvals` row in an explicitly approved state.
 *
 * `tests/agents/approval-gate.test.ts` proves this for the runtime's reference
 * tools. This file proves the roster did not open a hole in it: every attempt
 * below is aimed at a real role's real tool — Vinnie's `queue_social_post`
 * (external) and Teller's `propose_price_change` (storefront_write) — and each
 * one comes at the gate from a different direction.
 *
 * All of them must fail, and `RecordingOutbox` must never see the call.
 *
 * It also writes `lib/agents/roster/evidence/10-approval-gate-bypass.txt`.
 */

import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";

import { afterAll, beforeAll, describe, expect, it } from "vitest";

import {
  ApprovalGateError,
  invokeTool,
  silentLogger,
  type EffectGrant,
  type ToolExecutionContext,
} from "@/lib/agents";
import type { RosterRole } from "@/lib/agents/roster";

import {
  createRosterHarness,
  openRun,
  runRole,
  type RosterHarness,
} from "./support/harness";

const EVIDENCE = resolve(
  process.cwd(),
  "lib/agents/roster/evidence/10-approval-gate-bypass.txt",
);

const POST = {
  platform: "instagram" as const,
  caption: "A caption nobody approved.",
  sku: null,
  reason: "bypass attempt",
};

let harness: RosterHarness;
const attempts: string[] = [];

function record(attempt: string, outcome: string): void {
  attempts.push(`${attempt}\n    ${outcome}`);
}

function context(runId: string): ToolExecutionContext {
  return {
    runId,
    agentSlug: "social",
    toolCallId: "direct-call",
    now: new Date("2026-08-31T08:00:00.000Z"),
    logger: silentLogger,
    abortSignal: new AbortController().signal,
  };
}

function roleFor(slug: string): RosterRole {
  const role = harness.roster.roles.find(
    (candidate) => candidate.definition.slug === slug,
  );
  if (role === undefined) throw new Error(`no role ${slug}`);
  return role;
}

beforeAll(async () => {
  harness = await createRosterHarness();
}, 120_000);

afterAll(async () => {
  const body = [
    "=".repeat(78),
    "BYPASS ATTEMPTS ON A ROSTER AGENT'S EXTERNAL TOOL",
    "=".repeat(78),
    "Every line below is a deliberate attempt to make Vinnie's queue_social_post",
    "(effect: external) or Teller's propose_price_change (effect: storefront_write)",
    "fire without an approvals row in an approved state covering those exact",
    "arguments. Each comes at the gate from a different direction. All of them must",
    "fail, and the outbox must never see the call.",
    "",
    "Generated by tests/roster/approval-gate.test.ts against the seeded business.",
    "",
    ...attempts.map((line, index) => `${String(index + 1)}. ${line}\n`),
    "-".repeat(78),
    "The only route that worked was the legitimate one: a proposal raised by the",
    "run, an approvals row moved to 'approved' by the founder, and a grant minted",
    "from that row for those arguments — and even then nothing was delivered,",
    "because this build has no outbound channel at all.",
  ].join("\n");
  mkdirSync(dirname(EVIDENCE), { recursive: true });
  // Fresh uuids would make this file churn on every run without a behaviour
  // change, which is how evidence stops being read.
  const stable = body.replace(
    /[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}/gi,
    "id#1",
  );
  writeFileSync(EVIDENCE, `${stable.trimEnd()}\n`, "utf8");
  await harness.close();
});

describe("the roster cannot get around the approval gate", () => {
  it("refuses an external tool called directly with no grant", async () => {
    const run = await openRun(harness, roleFor("social"));
    const tool = run.tools.byName["queue_social_post"];
    expect(tool).toBeDefined();
    if (tool === undefined) return;

    await expect(invokeTool(tool, POST, context(run.runId))).rejects.toThrow(
      ApprovalGateError,
    );
    expect(run.outbox.externalCount()).toBe(0);
    record(
      "call queue_social_post directly, with no grant at all",
      'REFUSED  grant_missing — "external" cannot execute without an approval-backed grant; posts delivered: 0',
    );
  }, 60_000);

  it("refuses to mint a grant from an approval that is still pending", async () => {
    const run = await openRun(harness, roleFor("social"));
    const tool = run.tools.byName["queue_social_post"];
    expect(tool).toBeDefined();
    if (tool === undefined) return;

    const approval = await run.platform.approvals.request({
      definition: run.role.definition,
      agentId: run.agentId,
      runId: run.runId,
      tool,
      input: POST,
      presentation: { title: "post", summary: "unapproved" },
      rationale: null,
    });
    await expect(
      run.platform.approvals.grantFor({
        approvalId: approval.id,
        runId: run.runId,
        toolName: "queue_social_post",
        input: POST,
      }),
    ).rejects.toMatchObject({ code: "approval_not_approved" });
    expect(run.outbox.externalCount()).toBe(0);
    record(
      "raise the approval, then mint a grant while it is still pending",
      "REFUSED  approval_not_approved — a pending row grants nothing; posts delivered: 0",
    );
  }, 60_000);

  it("refuses a grant copied field for field from a real one", async () => {
    const run = await openRun(harness, roleFor("social"));
    const tool = run.tools.byName["queue_social_post"];
    expect(tool).toBeDefined();
    if (tool === undefined) return;

    const approval = await run.platform.approvals.request({
      definition: run.role.definition,
      agentId: run.agentId,
      runId: run.runId,
      tool,
      input: POST,
      presentation: { title: "post", summary: "for forging" },
      rationale: null,
    });
    await run.platform.approvals.decide({
      approvalId: approval.id,
      status: "approved",
      decidedBy: "founder",
      note: null,
    });
    const real = await run.platform.approvals.grantFor({
      approvalId: approval.id,
      runId: run.runId,
      toolName: "queue_social_post",
      input: POST,
    });
    const forged: EffectGrant = { ...real };

    await expect(
      invokeTool(tool, POST, context(run.runId), forged),
    ).rejects.toMatchObject({ code: "grant_forged" });
    expect(run.outbox.externalCount()).toBe(0);
    record(
      "forge a grant by spreading a real one into a new object",
      "REFUSED  grant_forged — the runtime keeps its own registry of minted grants; posts delivered: 0",
    );
  }, 60_000);

  it("refuses when the caption is edited after the founder approved it", async () => {
    const run = await openRun(harness, roleFor("social"));
    const tool = run.tools.byName["queue_social_post"];
    expect(tool).toBeDefined();
    if (tool === undefined) return;

    const approval = await run.platform.approvals.request({
      definition: run.role.definition,
      agentId: run.agentId,
      runId: run.runId,
      tool,
      input: POST,
      presentation: { title: "post", summary: "the approved caption" },
      rationale: null,
    });
    await run.platform.approvals.decide({
      approvalId: approval.id,
      status: "approved",
      decidedBy: "founder",
      note: null,
    });
    await expect(
      run.platform.approvals.grantFor({
        approvalId: approval.id,
        runId: run.runId,
        toolName: "queue_social_post",
        input: { ...POST, caption: "Something else entirely." },
      }),
    ).rejects.toMatchObject({ code: "grant_arguments_mismatch" });
    expect(run.outbox.externalCount()).toBe(0);
    record(
      "get one caption approved and then publish a different one",
      "REFUSED  grant_arguments_mismatch — the grant is fingerprinted over the exact arguments; posts delivered: 0",
    );
  }, 60_000);

  it("refuses to spend the same grant twice", async () => {
    const run = await openRun(harness, roleFor("social"));
    const tool = run.tools.byName["queue_social_post"];
    expect(tool).toBeDefined();
    if (tool === undefined) return;

    const approval = await run.platform.approvals.request({
      definition: run.role.definition,
      agentId: run.agentId,
      runId: run.runId,
      tool,
      input: POST,
      presentation: { title: "post", summary: "single use" },
      rationale: null,
    });
    await run.platform.approvals.decide({
      approvalId: approval.id,
      status: "approved",
      decidedBy: "founder",
      note: null,
    });
    const grant = await run.platform.approvals.grantFor({
      approvalId: approval.id,
      runId: run.runId,
      toolName: "queue_social_post",
      input: POST,
    });

    await invokeTool(tool, POST, context(run.runId), grant);
    expect(run.outbox.externalCount()).toBe(1);
    await expect(
      invokeTool(tool, POST, context(run.runId), grant),
    ).rejects.toMatchObject({ code: "grant_consumed" });
    expect(run.outbox.externalCount()).toBe(1);
    record(
      "approve once, post twice with the same grant",
      "REFUSED  grant_consumed — grants are single-use; the approved post went once and the second attempt did not",
    );
  }, 60_000);

  it("refuses a storefront write when the gate is skipped altogether", async () => {
    const run = await openRun(harness, roleFor("ledger"));
    // The price change Teller's own read would propose, taken straight from the
    // business — then run without ever going near gateToolCall().
    const margins = await harness.reads.margins();
    expect(margins.proposal).not.toBeNull();
    if (margins.proposal === null) return;

    const call = await run.store.createToolCall({
      runId: run.runId,
      messageId: null,
      toolName: "propose_price_change",
      arguments: { ...margins.proposal },
      isMutation: true,
      status: "pending",
    });
    const result = await run.platform.runtime.executeToolCall(
      run.runId,
      call.id,
    );

    expect(result.status).toBe("failed");
    expect(result.error ?? "").toContain("approval_required");
    expect(run.outbox.of("price_change")).toHaveLength(0);
    record(
      "skip the gate entirely and execute a proposed price change",
      `REFUSED  ${result.error ?? "?"} — price changes recorded: 0`,
    );
  }, 60_000);

  it("refuses to carry on after the founder says no", async () => {
    const role = roleFor("social");
    const run = await runRole(harness, role, {
      policy: (approval) =>
        approval.subjectType === "social_post"
          ? { approve: false, note: "No. I will write this one myself." }
          : { approve: true, note: "Fine." },
    });
    const calls = await run.store.listToolCalls(run.runId);
    const post = calls.find((call) => call.toolName === "queue_social_post");
    expect(post?.status).toBe("rejected");
    expect(run.outbox.of("social_post")).toHaveLength(0);
    expect(run.summary.status).toBe("succeeded");
    record(
      "have the founder decline, then let the run continue",
      `REFUSED  tool call recorded as "${post?.status ?? "missing"}"; posts delivered: 0. The run finished and reported the refusal instead of retrying.`,
    );
  }, 60_000);

  it("refuses a tool the role was never granted", async () => {
    const run = await openRun(harness, roleFor("marketing"));
    // Ari is B2C. queue_trade_outreach is Vic's, and Ari may not call it even
    // though it is registered in the same registry.
    const tool = run.tools.byName["queue_trade_outreach"];
    expect(tool).toBeDefined();
    if (tool === undefined) return;
    const call = await run.store.createToolCall({
      runId: run.runId,
      messageId: null,
      toolName: "queue_trade_outreach",
      arguments: {
        customerId: "x",
        account: "Any Bar",
        to: "bar@example.co.nz",
        subject: "hello",
        body: "hello",
        reason: "bypass attempt",
      },
      isMutation: true,
      status: "pending",
    });
    const gate = await run.platform.runtime.gateToolCall(run.runId, call.id);
    expect(gate.type).toBe("refused");
    expect(run.outbox.externalCount()).toBe(0);
    record(
      "have Ari (B2C) call Vic's (B2B) outreach tool",
      `REFUSED  ${gate.type === "refused" ? gate.reason : "?"}`,
    );
  }, 60_000);
});

/**
 * Keeping evidence files stable between runs.
 *
 * Several suites write a transcript into an evidence directory so the founder,
 * and a reviewer, can read what the code did without running it. Those files were
 * rewritten by every single `npx vitest run`, because each carried a fresh
 * uuid and a wall-clock timestamp. The working tree could therefore never be
 * clean while anyone was testing, and the churn was committed five times in
 * one session with nothing in it having changed.
 *
 * The rule these helpers enforce: **re-running produces a byte-identical file
 * unless the behaviour changed.** Anything that varies run to run and is not
 * itself the finding gets normalised away. Anything that IS the finding — a
 * measured timing spread, a refusal, a count — stays, but is recorded as the
 * assertion it supports rather than as a raw sample.
 */

/**
 * Replace every uuid with a stable `id#N` in order of first appearance.
 *
 * Identity between two mentions is preserved, which is the part that matters:
 * a reader still sees that the run in the header is the run in the transcript.
 */
export function stabiliseIds(body: string): string {
  const seen = new Map<string, string>();
  return body.replace(
    /[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}/gi,
    (match) => {
      const known = seen.get(match);
      if (known !== undefined) return known;
      const label = `id#${String(seen.size + 1)}`;
      seen.set(match, label);
      return label;
    },
  );
}

/**
 * The provenance line, without a clock in it.
 *
 * Naming the command is the useful half — it tells a reader how to regenerate
 * the file. The timestamp only ever said "someone ran the tests", which git
 * already records, and it was the reason every run produced a diff.
 */
export function generatedBy(command: string): string {
  return `generated by: ${command}`;
}

/**
 * Round a measured millisecond figure into a bucket wide enough that ordinary
 * run-to-run variance does not move it.
 *
 * For timing evidence the raw sample is noise — on a loaded machine the same
 * measurement moved from a 9ms spread to 1ms between two runs. What the file
 * exists to show is the assertion the numbers support, so record the bucket
 * and let the test keep asserting the real value.
 */
export function bucketMs(value: number, width = 25): string {
  const low = Math.floor(value / width) * width;
  return `${String(low)}-${String(low + width)}ms`;
}

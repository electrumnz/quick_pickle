import type { Metadata } from "next";

import { checkoutKind, currentCart } from "@/components/product/cart";
import { loadCatalogue } from "@/components/product/catalogue";
import {
  ADDED_PARAM,
  ERROR_PARAM,
  parseAdded,
} from "@/components/product/copy";
import { ShopView } from "@/components/product/ShopView";
import {
  collectionJsonLd,
  jsonLdText,
} from "@/components/product/structured-data";

/**
 * The collection page.
 *
 * `force-dynamic` is not laziness. Availability and stock counts are on this
 * page, and a prerendered stock count is a wrong stock count within the hour;
 * it is also what lets `npm run build` succeed in an environment with no
 * database, because nothing here runs at build time.
 */
export const dynamic = "force-dynamic";

export const metadata: Metadata = {
  title: "Shop",
  description:
    "Four brines and a box. 500 ml of the brine, not the pickle. Prices in NZD.",
  openGraph: {
    title: "Shop | Half Sour",
    description:
      "Four brines and a box. 500 ml of the brine, not the pickle. Prices in NZD.",
    url: "./",
  },
};

type SearchParams = Record<string, string | string[] | undefined>;

function first(value: string | string[] | undefined): string | null {
  if (typeof value === "string") return value;
  if (Array.isArray(value)) return value[0] ?? null;
  return null;
}

export default async function ShopPage({
  searchParams,
}: {
  searchParams: Promise<SearchParams>;
}) {
  const params = await searchParams;
  const catalogue = await loadCatalogue();
  const added = parseAdded(first(params[ADDED_PARAM]));
  const cart = added === null ? null : await currentCart();

  return (
    <>
      <script
        type="application/ld+json"
        // The payload is generated by this unit from typed records and escaped
        // in jsonLdText; no user input reaches it.
        dangerouslySetInnerHTML={{
          __html: jsonLdText(collectionJsonLd(catalogue.entries)),
        }}
      />
      <ShopView
        catalogue={catalogue}
        cart={cart}
        added={added}
        problem={first(params[ERROR_PARAM])}
        checkout={checkoutKind()}
      />
    </>
  );
}

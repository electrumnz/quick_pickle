import type { Metadata } from "next";
import { notFound } from "next/navigation";

import { checkoutIsLive, currentCart } from "@/components/product/cart";
import { loadCatalogue, loadEntry } from "@/components/product/catalogue";
import {
  ADDED_PARAM,
  ERROR_PARAM,
  parseAdded,
  PROBLEM,
} from "@/components/product/copy";
import { ProductView } from "@/components/product/ProductView";
import {
  breadcrumbJsonLd,
  jsonLdText,
  productJsonLd,
} from "@/components/product/structured-data";

/**
 * A product page.
 *
 * Dynamic for the same reason the collection page is: the availability chip,
 * the stock count and the buy control are all reads of live inventory, and a
 * prerendered one would be a picture of last week's stock. It also means a
 * build with no database is a build that never calls the provider.
 */
export const dynamic = "force-dynamic";

type Params = { handle: string };
type SearchParams = Record<string, string | string[] | undefined>;

function first(value: string | string[] | undefined): string | null {
  if (typeof value === "string") return value;
  if (Array.isArray(value)) return value[0] ?? null;
  return null;
}

export async function generateMetadata({
  params,
}: {
  params: Promise<Params>;
}): Promise<Metadata> {
  const { handle } = await params;
  const entry = await loadEntry(handle);
  if (entry === null) return { title: "No such bottle" };

  const description = [entry.descriptor, entry.line]
    .filter((part): part is string => part !== null)
    .join(" ");

  return {
    title: entry.title,
    description,
    openGraph: {
      type: "website",
      title: `${entry.title} | Half Sour`,
      description,
      url: "./",
    },
  };
}

export default async function ProductPage({
  params,
  searchParams,
}: {
  params: Promise<Params>;
  searchParams: Promise<SearchParams>;
}) {
  const [{ handle }, query] = await Promise.all([params, searchParams]);

  const entry = await loadEntry(handle);
  // The only 404 in this unit: a handle that is neither in the range nor in the
  // catalogue. A bottle the company makes always has a page, even when commerce
  // is down, because everything the page says about it is still true.
  if (entry === null) notFound();

  const catalogue = await loadCatalogue();
  const siblings = catalogue.entries.filter(
    (candidate) => candidate.kind !== "other",
  );
  const set =
    entry.kind === "set"
      ? null
      : (catalogue.entries.find((candidate) => candidate.kind === "set") ??
        null);

  const addedParam = parseAdded(first(query[ADDED_PARAM]));
  const added =
    addedParam !== null && addedParam.handle === entry.handle
      ? addedParam.quantity
      : null;
  const cart = added === null ? null : await currentCart();

  const problemCode = first(query[ERROR_PARAM]);
  const problem =
    problemCode === null ? null : (PROBLEM[problemCode] ?? PROBLEM.failed);

  return (
    <>
      <script
        type="application/ld+json"
        // Generated by this unit from typed records and escaped in jsonLdText;
        // nothing from the request reaches it.
        dangerouslySetInnerHTML={{
          __html: jsonLdText(productJsonLd(entry), breadcrumbJsonLd(entry)),
        }}
      />
      <ProductView
        entry={entry}
        siblings={siblings}
        set={set}
        degraded={catalogue.degraded}
        cart={cart}
        added={added}
        problem={problem ?? null}
        checkoutLive={checkoutIsLive()}
      />
    </>
  );
}

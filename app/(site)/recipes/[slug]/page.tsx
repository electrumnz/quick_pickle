import type { Metadata } from "next";
import { notFound } from "next/navigation";

import { jsonLdText } from "@/components/product/structured-data";
import { recipeJsonLd } from "@/components/site/recipe-schema";
import { recipeBySlug } from "@/components/site/recipes";
import { RecipeView } from "@/components/site/RecipeView";

/**
 * /recipes/[slug] — one recipe, individually shareable.
 *
 * The slug is the record's own slug, so a URL somebody pastes into a message is
 * the recipe and not a query against a list. `components/site/recipes.ts`
 * asserts the slugs are unique at module load: two recipes sharing one would
 * make a URL serve the wrong page, which is worse than serving none.
 *
 * Dynamic because the masthead reads the cart. Nothing else on the page does.
 */
export const dynamic = "force-dynamic";

type Params = { slug: string };

export async function generateMetadata({
  params,
}: {
  params: Promise<Params>;
}): Promise<Metadata> {
  const { slug } = await params;
  const recipe = recipeBySlug(slug);
  if (recipe === null) return { title: "No such recipe" };

  return {
    title: recipe.title,
    description: recipe.summary,
    openGraph: {
      type: "article",
      title: `${recipe.title} | Half Sour`,
      description: recipe.summary,
      url: "./",
    },
  };
}

export default async function RecipePage({
  params,
}: {
  params: Promise<Params>;
}) {
  const { slug } = await params;
  const recipe = recipeBySlug(slug);
  if (recipe === null) notFound();

  return (
    <>
      <script
        type="application/ld+json"
        // Generated by this unit from a typed record and escaped in jsonLdText;
        // nothing from the request reaches it.
        dangerouslySetInnerHTML={{ __html: jsonLdText(recipeJsonLd(recipe)) }}
      />
      <RecipeView recipe={recipe} />
    </>
  );
}

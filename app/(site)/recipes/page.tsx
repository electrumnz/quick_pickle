import type { Metadata } from "next";

import { jsonLdText } from "@/components/product/structured-data";
import { RECIPES } from "@/components/site/copy";
import { recipeListJsonLd } from "@/components/site/recipe-schema";
import { RecipeLibraryView } from "@/components/site/RecipeLibraryView";
import { ALL_RECIPES } from "@/components/site/recipes";

/**
 * /recipes — the library index.
 *
 * Dynamic for one reason only: the masthead reads the cart through the commerce
 * provider, exactly as the shop and product pages do. The recipes themselves are
 * typed records in `content/recipes/` and touch no database, so a build in an
 * environment with no Postgres still succeeds.
 */
export const dynamic = "force-dynamic";

export const metadata: Metadata = {
  title: RECIPES.title,
  description: RECIPES.metaDescription,
  openGraph: {
    type: "website",
    title: `${RECIPES.title} | Half Sour`,
    description: RECIPES.metaDescription,
    url: "./",
  },
};

export default function RecipesPage() {
  return (
    <>
      <script
        type="application/ld+json"
        // Generated by this unit from typed records and escaped in jsonLdText;
        // nothing from the request reaches it.
        dangerouslySetInnerHTML={{
          __html: jsonLdText(recipeListJsonLd(ALL_RECIPES)),
        }}
      />
      <RecipeLibraryView />
    </>
  );
}

"use server";

import { revalidatePath } from "next/cache";
import { redirect } from "next/navigation";

import { cleanTags, type ConsentState, type UsageRights } from "@/lib/assets";
import { deleteAsset } from "@/lib/assets/ingest";
import { assetLibrary } from "@/lib/assets/server";
import {
  ADMIN_CSRF_FIELD_NAME,
  assertAdminCsrf,
  requireAdminSession,
} from "@/lib/auth/server";

/**
 * The two things the founder can do to an asset once it is in.
 *
 * Both are Server Actions, and both do the same two checks first, in the same
 * order, for the same reason the sign-out form does: `requireAdminSession`
 * because a matcher change must never be able to open a door quietly, and
 * `assertAdminCsrf` because a state change reached through a form is a state
 * change another site would love to trigger.
 *
 * Neither of them can touch the consent gate's answer. `selectable_for_outbound`
 * is generated by Postgres from the columns below; these actions write the
 * columns, and the database recomputes the verdict.
 */

function text(form: FormData, name: string): string {
  const value = form.get(name);
  return typeof value === "string" ? value.trim() : "";
}

function optional(form: FormData, name: string): string | null {
  const value = text(form, name);
  return value === "" ? null : value;
}

const CONSENT: readonly ConsentState[] = [
  "no_people",
  "granted",
  "refused",
  "unrecorded",
];
const RIGHTS: readonly UsageRights[] = [
  "own_work",
  "permission_given",
  "licensed",
  "unknown",
];

export async function saveAssetMetadata(
  id: string,
  formData: FormData,
): Promise<void> {
  const { session } = await requireAdminSession();
  await assertAdminCsrf(text(formData, ADMIN_CSRF_FIELD_NAME));

  const consent = CONSENT.find(
    (state) => state === text(formData, "peopleConsent"),
  );
  const rights = RIGHTS.find(
    (right) => right === text(formData, "usageRights"),
  );

  const library = assetLibrary();
  await library.store.update(id, {
    title: text(formData, "title"),
    description: text(formData, "description"),
    // A model draft stops being called a draft when she has actually changed
    // the words — not merely because she pressed save on the screen it was on.
    // The agents are told which of the two they are reading, so the difference
    // has to be real.
    descriptionSource:
      text(formData, "descriptionSource") === "model_draft" &&
      text(formData, "description") !== text(formData, "descriptionWas")
        ? "model_edited"
        : undefined,
    occasion: optional(formData, "occasion"),
    occasionOn: optional(formData, "occasionOn"),
    tags: cleanTags(text(formData, "tags")),
    peoplePresent: formData.get("peoplePresent") !== null,
    ...(consent === undefined ? {} : { peopleConsent: consent }),
    consentNote: optional(formData, "consentNote"),
    ...(rights === undefined ? {} : { usageRights: rights }),
    credit: optional(formData, "credit"),
    rightsExpireOn: optional(formData, "rightsExpireOn"),
    variantIds: formData
      .getAll("variantIds")
      .filter((value): value is string => typeof value === "string"),
    operatorId: session.operatorId,
  });

  revalidatePath("/admin/assets");
  revalidatePath(`/admin/assets/${id}`);
  redirect(`/admin/assets/${id}?saved=1`);
}

export async function removeAsset(
  id: string,
  formData: FormData,
): Promise<void> {
  await requireAdminSession();
  await assertAdminCsrf(text(formData, ADMIN_CSRF_FIELD_NAME));

  const library = assetLibrary();
  await deleteAsset(id, { store: library.store, storage: library.storage });

  revalidatePath("/admin/assets");
  redirect("/admin/assets?deleted=1");
}

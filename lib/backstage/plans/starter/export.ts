/**
 * The starter drafts as Markdown files, so they can be read in the
 * repository without opening the back end.
 *
 * The back end starts with a set of drafts in Plans: how-to sheets, the
 * plans, two policies, the questions only a person can answer, the
 * compliance checklist and the lines of the budget. They are written once,
 * in this folder, as data. This turns the same data into documents under
 * `docs/starter/`, so whoever takes the business on can read them on the
 * day they are handed the repository.
 *
 * There is one source. `npm run docs:export` writes the files, and a test
 * (tests/backstage/starter-docs.test.ts) fails if what is in the folder is
 * not what this makes, so the two cannot drift apart.
 *
 * What these files are not: the live copy. Once somebody has changed a
 * sheet or answered a question in the back end, the back end is where that
 * lives. Every file says so at the top.
 */

import {
  COMPLIANCE_AREA_BLURB,
  COMPLIANCE_AREA_LABEL,
  COMPLIANCE_AREAS,
  COMPLIANCE_STATUS_LABEL,
  COST_BASIS_BLURB,
  COST_BASIS_LABEL,
} from "../labels";

import { STARTER_COMPLIANCE } from "./compliance";
import { STARTER_COSTS } from "./costs";
import { STARTER_HOW_TOS } from "./how-tos";
import { STARTER_PLANS } from "./plans";
import { STARTER_POLICIES } from "./policies";
import { STARTER_QUESTIONS } from "./questions";
import { LINK } from "./terms";
import type { StarterDocument } from "./types";

/**
 * Where the shop is. The drafts link to screens of the back end, and a link
 * in a file on GitHub has to say the whole address. Change it here when the
 * shop has its own domain, and run `npm run docs:export`.
 */
export const LIVE_SITE = "https://quickpickle.co.nz";

/** The folder the files are written to, from the top of the repository. */
export const STARTER_DOCS_DIR = "docs/starter";

export type DocFile = {
  /** From the top of the repository. */
  readonly path: string;
  readonly markdown: string;
};

const MADE_BY =
  "<!-- Written by `npm run docs:export` from lib/backstage/plans/starter. Do not edit this file: change the source and run it again. -->";

type Shelf = {
  readonly folder: string;
  readonly heading: string;
  readonly blurb: string;
  readonly documents: readonly StarterDocument[];
};

const SHELVES: readonly Shelf[] = [
  {
    folder: "how-to",
    heading: "How-to sheets",
    blurb: "Checklists to follow on the day.",
    documents: STARTER_HOW_TOS,
  },
  {
    folder: "plans",
    heading: "Plans",
    blurb: "Where the business is going and how. Drafts, with blanks to fill.",
    documents: STARTER_PLANS,
  },
  {
    folder: "policies",
    heading: "Policies",
    blurb: "The rules the business holds itself to.",
    documents: STARTER_POLICIES,
  },
];

const inOrder = (documents: readonly StarterDocument[]) =>
  [...documents].sort((a, b) => a.sort - b.sort);

/** Where each draft's file is, by the draft's address in the back end. */
function filesBySlug(): Map<string, string> {
  const out = new Map<string, string>();
  for (const shelf of SHELVES) {
    for (const document of shelf.documents) {
      out.set(document.slug, `${shelf.folder}/${document.slug}.md`);
    }
  }
  return out;
}

/** `a/b.md` as seen from `a/c.md`, or from the folder's own top. */
function relative(from: string, to: string): string {
  const depth = from.split("/").length - 1;
  return depth === 0 ? to : `${"../".repeat(depth)}${to}`;
}

/**
 * A draft's links, made to work in a file. A link to another draft goes to
 * that draft's own file here. A link to a screen of the back end is given
 * the shop's address in front.
 */
function withLinks(body: string, from: string): string {
  const files = filesBySlug();
  const docPrefix = LINK.doc("");
  return body.replace(/\]\((\/[^)\s]*)\)/g, (whole, address: string) => {
    if (address.startsWith(docPrefix)) {
      const slug = address.slice(docPrefix.length).split(/[?#]/)[0] ?? "";
      const file = files.get(slug);
      if (file !== undefined) return `](${relative(from, file)})`;
    }
    return `](${LIVE_SITE}${address})`;
  });
}

function liveCopy(what: string, address: string): string {
  return `> This is the starting draft that ships with the back end, as it was written. The copy people work from is in the back end, under [${what}](${LIVE_SITE}${address}), and may have been changed there since. This file does not follow those changes.`;
}

function documentFile(shelf: Shelf, document: StarterDocument): DocFile {
  const path = `${shelf.folder}/${document.slug}.md`;
  const markdown = [
    MADE_BY,
    "",
    `# ${document.title}`,
    "",
    `> ${document.summary}`,
    ">",
    liveCopy("Plans", LINK.doc(document.slug)),
    "",
    withLinks(document.body.trim(), path),
    "",
  ].join("\n");
  return { path, markdown };
}

function questionsFile(): DocFile {
  const path = "QUESTIONS.md";
  const blocking = STARTER_QUESTIONS.filter((q) => q.blocksLaunch).length;
  const lines: string[] = [
    MADE_BY,
    "",
    "# Questions only a person can answer",
    "",
    `> ${String(STARTER_QUESTIONS.length)} questions. ${String(blocking)} of them stand between the site and taking money, and say so.`,
    ">",
    "> Nothing here is an answer. Each says why it matters, who to ask and where the question came from.",
    ">",
    liveCopy("Plans, Questions", LINK.questions),
    "",
  ];
  let topic = "";
  for (const question of STARTER_QUESTIONS) {
    if (question.topic !== topic) {
      topic = question.topic;
      lines.push(`## ${topic}`, "");
    }
    lines.push(
      `### ${question.question}`,
      "",
      `- **In the way of launch:** ${question.blocksLaunch ? "yes" : "no"}`,
      `- **Who to ask:** ${question.askOf}`,
      `- **Why it matters:** ${question.why}`,
      `- **Where it came from:** ${question.source}`,
      "",
    );
  }
  return { path, markdown: withLinks(lines.join("\n"), path) };
}

function complianceFile(): DocFile {
  const path = "COMPLIANCE.md";
  const lines: string[] = [
    MADE_BY,
    "",
    "# The compliance checklist",
    "",
    "> A short list of things to look into, for a small business selling a packaged food online in New Zealand. One line each, in plain words, with the body to ask.",
    ">",
    "> **It is not legal advice.** It was written by an AI assistant on 12 November 2026 and has not been read by a lawyer. It does not say what applies in this business's exact case: that is for the owner to find out from the bodies named. Every line starts as something to check for that reason.",
    ">",
    liveCopy("Plans, Compliance", LINK.compliance),
    "",
  ];
  for (const area of COMPLIANCE_AREAS) {
    const items = STARTER_COMPLIANCE.filter((item) => item.area === area);
    if (items.length === 0) continue;
    lines.push(
      `## ${COMPLIANCE_AREA_LABEL[area]}`,
      "",
      COMPLIANCE_AREA_BLURB[area],
      "",
    );
    for (const item of items) {
      lines.push(
        `### ${item.title}`,
        "",
        item.detail,
        "",
        `- **Where it comes from:** ${item.basis}`,
        `- **Starts as:** ${COMPLIANCE_STATUS_LABEL[item.status]}`,
        "",
      );
    }
  }
  return { path, markdown: withLinks(lines.join("\n"), path) };
}

function costsFile(): DocFile {
  const path = "COSTS.md";
  const lines: string[] = [
    MADE_BY,
    "",
    "# What a pack costs to make and send",
    "",
    "> The lines of the budget, each with what to fill in and where the figure comes from. Every amount starts at nothing: none of them is guessed.",
    ">",
    liveCopy("Plans, Budget", LINK.budget),
    "",
  ];
  const bases = [...new Set(STARTER_COSTS.map((cost) => cost.basis))];
  for (const basis of bases) {
    lines.push(
      `## ${COST_BASIS_LABEL[basis]}`,
      "",
      COST_BASIS_BLURB[basis],
      "",
    );
    for (const cost of STARTER_COSTS.filter((each) => each.basis === basis)) {
      lines.push(`- **${cost.name}.** ${cost.notes}`);
    }
    lines.push("");
  }
  return { path, markdown: withLinks(lines.join("\n"), path) };
}

function indexFile(): DocFile {
  const lines: string[] = [
    MADE_BY,
    "",
    "# The drafts the back end starts with",
    "",
    "The back end opens with a set of drafts in **Plans**, so the area does not start empty. These are the same drafts, as files, so they can be read here.",
    "",
    `Once the back end has been used, [Plans](${LIVE_SITE}${LINK.plans}) is where the working copy lives. A sheet that has been changed there, or a question that has been answered there, is not changed here.`,
    "",
    "Everything was written for a New Zealand business selling a packaged food online. Only what was known on 12 November 2026 is stated as fact. The rest is a question to answer, a blank to fill in (`____`), or an assumption marked as one.",
    "",
    "## Lists",
    "",
    `- [Questions only a person can answer](QUESTIONS.md): ${String(STARTER_QUESTIONS.length)} of them, by topic.`,
    `- [The compliance checklist](COMPLIANCE.md): ${String(STARTER_COMPLIANCE.length)} things to look into. Not legal advice.`,
    `- [What a pack costs to make and send](COSTS.md): the ${String(STARTER_COSTS.length)} lines of the budget.`,
    "",
  ];
  for (const shelf of SHELVES) {
    lines.push(`## ${shelf.heading}`, "", shelf.blurb, "");
    for (const document of inOrder(shelf.documents)) {
      lines.push(
        `- [${document.title}](${shelf.folder}/${document.slug}.md): ${document.summary}`,
      );
    }
    lines.push("");
  }
  return { path: "README.md", markdown: lines.join("\n") };
}

/**
 * Every file, unformatted, with its path inside `docs/starter/`. Whoever
 * writes them runs the result through the repository's formatter first, so
 * what is committed passes the same check as everything else.
 */
export function starterDocFiles(): DocFile[] {
  const files: DocFile[] = [
    indexFile(),
    questionsFile(),
    complianceFile(),
    costsFile(),
  ];
  for (const shelf of SHELVES) {
    for (const document of inOrder(shelf.documents)) {
      files.push(documentFile(shelf, document));
    }
  }
  return files;
}

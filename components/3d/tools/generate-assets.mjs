#!/usr/bin/env node
/**
 * Generates the 3D assets that ship with the bottle system:
 *   public/3d/env/studio-softbox.hdr     bespoke equirectangular studio IBL
 *   public/3d/labels/placeholder-label.png  UV registration card
 *
 * Both are produced here rather than fetched so the scene has no runtime
 * dependency on a CDN, and so the HDRI matches the light rig exactly.
 *
 *   node components/3d/tools/generate-assets.mjs
 */
import { writeFileSync, mkdirSync } from "node:fs";
import { deflateSync } from "node:zlib";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "../../..");

/* ---------------------------------------------------------------- HDRI --- */

const W = 512;
const H = 256;

const clamp = (v, a, b) => Math.min(b, Math.max(a, v));
const smoothstep = (a, b, x) => {
  const t = clamp((x - a) / (b - a), 0, 1);
  return t * t * (3 - 2 * t);
};

/** Soft angular blob on the sphere, in degrees. */
function blob(az, el, azC, elC, azR, elR, soft) {
  let d = az - azC;
  while (d > 180) d -= 360;
  while (d < -180) d += 360;
  const a = 1 - smoothstep(azR * (1 - soft), azR, Math.abs(d));
  const b = 1 - smoothstep(elR * (1 - soft), elR, Math.abs(el - elC));
  return a * b;
}

function radiance(az, el) {
  // Deep neutral room. The crisp softbox reflections come from Lightformers
  // in the scene, so the HDRI only has to supply the room the glass sits in
  // — a hard source here would double up with the rig.
  const up = clamp((el + 90) / 180, 0, 1);
  const base = 0.012 + 0.055 * Math.pow(up, 1.6);
  let r = base * 0.98;
  let g = base;
  let b = base * 1.16;

  // Broad overhead diffusion: the ceiling of the room.
  const ceil = Math.pow(clamp((el - 20) / 70, 0, 1), 1.35) * 0.85;
  r += ceil * 0.95;
  g += ceil * 0.97;
  b += ceil * 1.0;

  // A gentle wash from the key side so the room is not symmetric — perfectly
  // even lighting is the flattest, cheapest-looking thing you can do to glass.
  r += blob(az, el, -58, 6, 78, 62, 0.9) * 0.16;
  g += blob(az, el, -58, 6, 78, 62, 0.9) * 0.16;
  b += blob(az, el, -58, 6, 78, 62, 0.9) * 0.17;

  // Cool bounce opposite.
  const fill = blob(az, el, 74, 2, 62, 55, 0.95) * 0.075;
  r += fill * 0.8;
  g += fill * 0.92;
  b += fill * 1.15;

  // Warm haze low behind, which is what gives brine its glow from within.
  const rim = blob(az, el, 178, 4, 44, 34, 0.85) * 0.5;
  r += rim * 1.15;
  g += rim * 1.0;
  b += rim * 0.74;

  // Floor falloff.
  const floor = 1 - smoothstep(-40, -8, el);
  r *= 1 - floor * 0.72;
  g *= 1 - floor * 0.72;
  b *= 1 - floor * 0.72;

  return [r, g, b];
}

function toRGBE(r, g, b) {
  const m = Math.max(r, g, b);
  if (m < 1e-32) return [0, 0, 0, 0];
  const e = Math.ceil(Math.log2(m));
  const s = 255.9999 / Math.pow(2, e);
  return [
    clamp(Math.floor(r * s), 0, 255),
    clamp(Math.floor(g * s), 0, 255),
    clamp(Math.floor(b * s), 0, 255),
    clamp(e + 128, 0, 255),
  ];
}

/** Radiance adaptive run-length encoding, per component, per scanline. */
function rleScanline(comp, out) {
  let i = 0;
  const n = comp.length;
  while (i < n) {
    let run = 1;
    while (i + run < n && comp[i + run] === comp[i] && run < 127) run++;
    if (run >= 4) {
      out.push(128 + run, comp[i]);
      i += run;
    } else {
      let lit = 0;
      while (
        i + lit < n &&
        lit < 128 &&
        !(
          lit + 3 < n - i &&
          comp[i + lit] === comp[i + lit + 1] &&
          comp[i + lit] === comp[i + lit + 2] &&
          comp[i + lit] === comp[i + lit + 3]
        )
      ) {
        lit++;
      }
      if (lit === 0) lit = 1;
      out.push(lit);
      for (let k = 0; k < lit; k++) out.push(comp[i + k]);
      i += lit;
    }
  }
}

function writeHDR(path) {
  const header = Buffer.from(
    `#?RADIANCE\n# HALF SOUR studio softbox, generated by components/3d/tools/generate-assets.mjs\nFORMAT=32-bit_rle_rgbe\n\n-Y ${H} +X ${W}\n`,
    "ascii",
  );
  const chunks = [header];
  const R = new Uint8Array(W);
  const G = new Uint8Array(W);
  const B = new Uint8Array(W);
  const E = new Uint8Array(W);
  for (let y = 0; y < H; y++) {
    // Row 0 is the top of the image (+Y), matching -Y H ordering.
    const el = 90 - (y + 0.5) * (180 / H);
    for (let x = 0; x < W; x++) {
      const az = (x + 0.5) * (360 / W) - 180;
      const [r, g, b] = radiance(az, el);
      const [rr, gg, bb, ee] = toRGBE(r, g, b);
      R[x] = rr;
      G[x] = gg;
      B[x] = bb;
      E[x] = ee;
    }
    const out = [2, 2, (W >> 8) & 0xff, W & 0xff];
    rleScanline(R, out);
    rleScanline(G, out);
    rleScanline(B, out);
    rleScanline(E, out);
    chunks.push(Buffer.from(out));
  }
  const buf = Buffer.concat(chunks);
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, buf);
  return buf.length;
}


function crc32(buf) {
  let c;
  const table = [];
  for (let n = 0; n < 256; n++) {
    c = n;
    for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1;
    table[n] = c >>> 0;
  }
  let crc = 0xffffffff;
  for (let i = 0; i < buf.length; i++)
    crc = table[(crc ^ buf[i]) & 0xff] ^ (crc >>> 8);
  return (crc ^ 0xffffffff) >>> 0;
}

function chunk(type, data) {
  const len = Buffer.alloc(4);
  len.writeUInt32BE(data.length);
  const body = Buffer.concat([Buffer.from(type, "ascii"), data]);
  const crc = Buffer.alloc(4);
  crc.writeUInt32BE(crc32(body));
  return Buffer.concat([len, body, crc]);
}

function writePNG(path, width, height, rgba) {
  const raw = Buffer.alloc((width * 4 + 1) * height);
  for (let y = 0; y < height; y++) {
    raw[y * (width * 4 + 1)] = 0;
    rgba.copy(raw, y * (width * 4 + 1) + 1, y * width * 4, (y + 1) * width * 4);
  }
  const ihdr = Buffer.alloc(13);
  ihdr.writeUInt32BE(width, 0);
  ihdr.writeUInt32BE(height, 4);
  ihdr[8] = 8;
  ihdr[9] = 6;
  const png = Buffer.concat([
    Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]),
    chunk("IHDR", ihdr),
    chunk("IDAT", deflateSync(raw, { level: 9 })),
    chunk("IEND", Buffer.alloc(0)),
  ]);
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, png);
  return png.length;
}

function writeLabel(path) {
  // u wraps the body once, v runs bottom-to-top up the label band.
  const w = 1024;
  const h = 420;
  const px = Buffer.alloc(w * h * 4);
  const set = (x, y, r, g, b, a = 255) => {
    if (x < 0 || y < 0 || x >= w || y >= h) return;
    const i = (y * w + x) * 4;
    px[i] = r;
    px[i + 1] = g;
    px[i + 2] = b;
    px[i + 3] = a;
  };
  const paper = [242, 237, 225];
  const ink = [36, 40, 34];
  for (let y = 0; y < h; y++) {
    for (let x = 0; x < w; x++) {
      // Faint laid-paper tooth so the label does not read as flat vinyl.
      const n = ((Math.sin(x * 1.7) + Math.sin(y * 2.3)) * 2.4) | 0;
      set(x, y, paper[0] + n, paper[1] + n, paper[2] + n);
    }
  }
  const rect = (x0, y0, x1, y1, c) => {
    for (let y = y0; y < y1; y++)
      for (let x = x0; x < x1; x++) set(x, y, c[0], c[1], c[2]);
  };
  const frame = (x0, y0, x1, y1, t, c) => {
    rect(x0, y0, x1, y0 + t, c);
    rect(x0, y1 - t, x1, y1, c);
    rect(x0, y0, x0 + t, y1, c);
    rect(x1 - t, y0, x1, y1, c);
  };
  frame(18, 18, w - 18, h - 18, 3, ink);
  frame(30, 30, w - 30, h - 30, 1, ink);

  const text = (str, cx, cy, scale, c) => {
    const glyphW = 6 * scale;
    const total = str.length * glyphW - scale;
    let x0 = Math.round(cx - total / 2);
    const y0 = Math.round(cy - (7 * scale) / 2);
    for (const ch of str.toUpperCase()) {
      const rows = FONT[ch] ?? FONT[" "];
      for (let r = 0; r < 7; r++) {
        for (let k = 0; k < 5; k++) {
          if (rows[r][k] === "1")
            rect(
              x0 + k * scale,
              y0 + r * scale,
              x0 + (k + 1) * scale,
              y0 + (r + 1) * scale,
              c,
            );
        }
      }
      x0 += glyphW;
    }
  };

  text("HALF SOUR", w / 2, 150, 9, ink);
  rect(w / 2 - 200, 210, w / 2 + 200, 213, ink);
  text("PLACEHOLDER LABEL", w / 2, 250, 3, ink);
  text("SWAP VIA LABEL.TEXTUREURL", w / 2, 290, 3, ink);
  text("U WRAPS BODY - V RUNS UP BAND", w / 2, 330, 3, ink);

  // Registration ticks every eighth of the wrap, so any twist or stretch in
  // the mapping is obvious on the model at a glance.
  for (let i = 0; i <= 8; i++) {
    const x = Math.round((i / 8) * (w - 1));
    const long = i % 2 === 0;
    rect(Math.max(0, x - 1), 40, Math.min(w, x + 2), long ? 76 : 60, ink);
    rect(
      Math.max(0, x - 1),
      h - (long ? 76 : 60),
      Math.min(w, x + 2),
      h - 40,
      ink,
    );
  }
  // Seam markers: these two must meet exactly on the model.
  rect(0, h / 2 - 40, 6, h / 2 + 40, [178, 62, 48]);
  rect(w - 6, h / 2 - 40, w, h / 2 + 40, [178, 62, 48]);

  return writePNG(path, w, h, px);
}


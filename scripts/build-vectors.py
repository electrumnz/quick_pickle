"""Build clean SVG assets + TS path modules from Ashleigh's vector concept pages.

Usage: python build_vectors.py <pack_extracted_dir> <repo_root>
Reads concept-p1/p2/p3.svg (Cairo output: flat <path> list). Writes:
  public/brand/lucky-run.svg, lucky-up.svg, lockup-stacked.svg
  lib/brand/art/lucky-run.ts, lucky-up.ts, lockup-letters.ts
"""
import re, sys, json, os
import xml.etree.ElementTree as ET

src, repo = sys.argv[1], sys.argv[2]
NS = {'s': 'http://www.w3.org/2000/svg'}

def tone(fill):
    if fill is None: return None
    if '13.33' in fill: return 'navy'
    if '94.9' in fill or '95.29' in fill: return 'cream'
    if '91.37' in fill: return 'pink'
    if '68.2' in fill: return 'olive'
    raise SystemExit('unknown fill ' + fill)

NUM = re.compile(r'-?\d+(?:\.\d+)?(?:e-?\d+)?')

def top_paths(path):
    root = ET.parse(path).getroot()
    out = []
    def walk(el, in_defs):
        tag = el.tag.split('}')[-1]
        if tag in ('defs', 'clipPath'): return
        if tag == 'path':
            out.append((tone(el.get('fill')), el.get('d')))
        for c in el: walk(c, in_defs)
    walk(root, False)
    return out

def nums(d):
    return [float(x) for x in NUM.findall(d)]

def xform(d, sx=1.0, tx=0.0, ty=0.0, prec=2):
    """Scale+translate an absolute-command path (Cairo emits only M L C Z) and round."""
    toks = re.findall(r'[MLCZ]|-?\d+(?:\.\d+)?', d)
    out = []
    i = 0
    coord_index = 0
    for t in toks:
        if t in 'MLCZ':
            out.append(t)
            coord_index = 0
        else:
            v = float(t) * sx + (tx if coord_index % 2 == 0 else ty)
            s = f'{v:.{prec}f}'.rstrip('0').rstrip('.')
            if s == '-0': s = '0'
            out.append(s)
            coord_index += 1
    # compact join: command letters need no spaces around them
    res = ''
    prev_cmd = True
    for t in out:
        if t in 'MLCZ':
            res += t; prev_cmd = True
        else:
            if not prev_cmd and not t.startswith('-'): res += ' '
            res += t; prev_cmd = False
    return res

def bbox(paths):
    xs, ys = [], []
    for _, d in paths:
        n = nums(d)
        xs += n[0::2]; ys += n[1::2]
    return min(xs), min(ys), max(xs), max(ys)

# verify Cairo only uses absolute M/L/C/Z
for n in (1, 2, 3):
    for _, d in top_paths(f'{src}/concept-p{n}.svg'):
        letters = set(re.findall(r'[A-Za-z]', d))
        assert letters <= set('MLCZ'), letters

p1 = top_paths(f'{src}/concept-p1.svg')
p2 = top_paths(f'{src}/concept-p2.svg')
p3 = top_paths(f'{src}/concept-p3.svg')
print('counts', len(p1), len(p2), len(p3))

# ---- p2: the running cat. index 0 is the pink page ground.
run = p2[1:]
RUN_GROUPS = {
    'burst': {31, 33, 35, 36, 39, 42, 43},
    'speed': {29, 32, 44},
    'dust': {25, 27, 37, 38, 41},
    'ground': {19, 28, 45},
}
# ---- p1: the flying-up cat. Top-level paths: 0 = ground; then cat paths; last 12 pink marks are an invisible signature.
# top_paths() skips <use> glyphs (they have no d) so indices differ from the browser catalogue: find by fill/order.
up_all = p1[1:]
up = [p for p in up_all if p[0] != 'pink']
print('up paths', len(up))

def pad_box(b, pad):
    x0, y0, x1, y1 = b
    return x0 - pad, y0 - pad, x1 + pad, y1 + pad

def write_svg(name, groups, box, title):
    x0, y0, x1, y1 = box
    w, h = x1 - x0, y1 - y0
    FILL = {'navy': '#22235c', 'cream': '#f2e3c2', 'olive': '#afb135', 'pink': '#ea2563'}
    parts = [f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {w:.2f} {h:.2f}" role="img"><title>{title}</title>']
    for gname, items in groups:
        parts.append(f'<g id="{gname}">' if gname else '<g>')
        for t, d in items:
            parts.append(f'<path fill="{FILL[t]}" d="{d}"/>')
        parts.append('</g>')
    parts.append('</svg>')
    out = os.path.join(repo, 'public/brand', name)
    os.makedirs(os.path.dirname(out), exist_ok=True)
    open(out, 'w').write(''.join(parts))
    print(name, f'{w:.1f}x{h:.1f}', os.path.getsize(out), 'bytes')
    return w, h

def write_ts(name, const, groups, w, h, doc):
    out = os.path.join(repo, 'lib/brand/art', name)
    os.makedirs(os.path.dirname(out), exist_ok=True)
    body = {g: [[t, d] for t, d in items] for g, items in groups}
    with open(out, 'w') as f:
        f.write('// GENERATED by scripts/build-vectors.py from the official concept art. Do not edit by hand.\n')
        f.write(f'// {doc}\n')
        f.write('import type { ArtGroups } from "./types";\n\n')
        f.write(f'export const {const}_SIZE = {{ width: {w:.2f}, height: {h:.2f} }} as const;\n\n')
        f.write(f'export const {const}: ArtGroups = ')
        f.write(json.dumps(body, separators=(',', ':')))
        f.write(';\n')
    print(name, os.path.getsize(out), 'bytes')

# --- lucky-run
rb = pad_box(bbox(run), 2)
def grp_run(idx_set):
    return [(t, xform(d, 1, -rb[0], -rb[1])) for i, (t, d) in enumerate(p2) if i in idx_set]
special = set().union(*RUN_GROUPS.values())
body_idx = {i for i in range(1, len(p2)) if i not in special}
run_groups = [('ground', grp_run(RUN_GROUPS['ground'])), ('dust', grp_run(RUN_GROUPS['dust'])), ('speed', grp_run(RUN_GROUPS['speed'])), ('body', grp_run(body_idx)), ('burst', grp_run(RUN_GROUPS['burst']))]
# keep original paint order inside body (already index order)
w, h = write_svg('lucky-run.svg', run_groups, rb, 'Lucky the cat running with a pickle')
write_ts('lucky-run.ts', 'LUCKY_RUN', run_groups, w, h, 'Lucky running (concept page 2), knockout palette for pink grounds.')

# --- lucky-up
ub = pad_box(bbox(up), 2)
# burst marks around the raised pickle: small navy paths near the fist (x 190-256, y 43-116 in page units)
def is_up_burst(t, d):
    n = nums(d); xs, ys = n[0::2], n[1::2]
    bw, bh = max(xs) - min(xs), max(ys) - min(ys)
    cx, cy = (max(xs) + min(xs)) / 2, (max(ys) + min(ys)) / 2
    near_left = 188 <= cx <= 212 and 48 <= cy <= 112
    near_right = 238 <= cx <= 250 and 50 <= cy <= 88
    return t == 'navy' and bw < 16 and bh < 18 and (near_left or near_right)
up_burst = [(t, xform(d, 1, -ub[0], -ub[1])) for t, d in up if is_up_burst(t, d)]
up_body = [(t, xform(d, 1, -ub[0], -ub[1])) for t, d in up if not is_up_burst(t, d)]
print('up burst marks', len(up_burst))
up_groups = [('body', up_body), ('burst', up_burst)]
w, h = write_svg('lucky-up.svg', up_groups, ub, 'Lucky the cat flying up with a pickle raised')
write_ts('lucky-up.ts', 'LUCKY_UP', up_groups, w, h, 'Lucky flying up (concept page 1), knockout palette for pink grounds.')

# --- stacked lockup: letters from p3 (1..22), cat = p2 art placed with the measured transform.
letters_shadow = p3[1:12]
letters_face = p3[12:23]
# solve scale/translate from the main outline path (p2[18] vs p3[40])
a, b = nums(p2[18][1]), nums(p3[40][1])
assert p2[18][0] == 'navy' and p3[40][0] == 'navy'
ax0, ax1, ay0, ay1 = min(a[0::2]), max(a[0::2]), min(a[1::2]), max(a[1::2])
bx0, bx1, by0, by1 = min(b[0::2]), max(b[0::2]), min(b[1::2]), max(b[1::2])
sx = (bx1 - bx0) / (ax1 - ax0); sy = (by1 - by0) / (ay1 - ay0)
s = (sx + sy) / 2
tx = bx0 - ax0 * s; ty = by0 - ay0 * s
print(f'cat-in-lockup transform: scale {sx:.5f}/{sy:.5f} -> {s:.5f}, translate {tx:.3f},{ty:.3f}')
lb = pad_box(bbox(p3[1:]), 2)
def L(items): return [(t, xform(d, 1, -lb[0], -lb[1])) for t, d in items]
lock_groups_static = [('letters-shadow', L(letters_shadow)), ('letters', L(letters_face)), ('cat', L(p3[23:]))]
w, h = write_svg('lockup-stacked.svg', lock_groups_static, lb, 'Quick Pickle')
write_ts('lockup-letters.ts', 'LOCKUP_LETTERS', [('shadow', L(letters_shadow)), ('face', L(letters_face))], w, h,
         f'Stacked QUICK / PICKLE letters (concept page 3). Cat placement inside this box: translate({tx - lb[0]:.3f} {ty - lb[1]:.3f}) scale({s:.5f}) applied to lucky-run page coordinates minus its own offset ({rb[0]:.3f}, {rb[1]:.3f}).')
meta = {'lockup': {'w': w, 'h': h}, 'catInLockup': {'scale': s, 'tx': tx - lb[0] + rb[0] * s, 'ty': ty - lb[1] + rb[1] * s}}
print(json.dumps(meta))
